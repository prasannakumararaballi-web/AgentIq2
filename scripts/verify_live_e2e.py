"""Comprehensive live end-to-end audit and verification script for AgentIQ v2."""

import hashlib
import io
import json
from pathlib import Path
import sys
import time
from uuid import UUID, uuid4
import pandas as pd
from fastapi.testclient import TestClient

# Ensure workspace paths
BASE_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BASE_DIR))
sys.path.insert(0, str(BASE_DIR / "packages"))
sys.path.insert(0, str(BASE_DIR / "apps"))

from apps.api.main import app
from apps.api.security.jwt_validator import SupabaseJWTValidator, set_jwt_validator
from agentiq_core.db.session import get_db_session
from tests.conftest import (
    ADMIN_USER_ID,
    PROJECT_A_ID,
    WORKSPACE_A_ID,
    TEST_JWT_SECRET,
    make_jwt,
    test_engine,
    TestSessionFactory,
    Base,
    User,
    Workspace,
    WorkspaceMember,
    Project,
)
from agentiq_core.engine.detectors import ALL_DETECTORS
from agentiq_core.engine.tabular import TabularEngine
from agentiq_core.storage.local import LocalStorageService


def run_e2e_verification():
    print("=" * 80)
    print("AGENTIQ v2 - COMPREHENSIVE LIVE END-TO-END VERIFICATION")
    print("=" * 80)

    # Initialize test security and database overrides for standalone execution
    validator = SupabaseJWTValidator(
        jwt_secret=TEST_JWT_SECRET,
        audience="authenticated",
    )
    set_jwt_validator(validator)

    import asyncio
    async def _init_db():
        async with test_engine.begin() as conn:
            await conn.run_sync(Base.metadata.create_all)
        async with TestSessionFactory() as session:
            existing_user = await session.get(User, ADMIN_USER_ID)
            if not existing_user:
                admin_u = User(id=ADMIN_USER_ID, email="admin@example.com", full_name="Admin User")
                session.add(admin_u)
                ws_a = Workspace(id=WORKSPACE_A_ID, name="Workspace A", slug="workspace-a")
                session.add(ws_a)
                m1 = WorkspaceMember(workspace_id=WORKSPACE_A_ID, user_id=ADMIN_USER_ID, role="admin")
                session.add(m1)
                proj_a = Project(id=PROJECT_A_ID, workspace_id=WORKSPACE_A_ID, name="Project Alpha")
                session.add(proj_a)
                await session.commit()

    asyncio.run(_init_db())

    async def _get_test_db():
        async with TestSessionFactory() as session:
            try:
                yield session
                await session.commit()
            except Exception:
                await session.rollback()
                raise
    app.dependency_overrides[get_db_session] = _get_test_db

    results = {}

    # --------------------------------------------------------------------------
    # 1. Start / Probe FastAPI & Next.js readiness
    # --------------------------------------------------------------------------
    print("\n[1/15] Verifying FastAPI Application & Next.js Build...")
    client = TestClient(app)
    health_res = client.get("/health")
    if health_res.status_code == 200 and health_res.json().get("status") == "healthy":
        print(f"  [OK] FastAPI /health check 200 OK: {health_res.json()}")
        results["1_service_readiness"] = "VERIFIED"
    else:
        print(f"  [FAIL] FastAPI /health check failed: {health_res.status_code} {health_res.text}")
        results["1_service_readiness"] = "FAILED"

    # --------------------------------------------------------------------------
    # 2. Test One-Click Demo Authentication
    # --------------------------------------------------------------------------
    print("\n[2/15] Testing One-Click Demo Authentication Token...")
    # Demo token generated by /api/demo-token route uses test secret and Admin UUID
    demo_jwt = make_jwt(user_id=ADMIN_USER_ID, email="admin@example.com")
    admin_headers = {
        "Authorization": f"Bearer {demo_jwt}",
        "X-Workspace-ID": str(WORKSPACE_A_ID),
    }
    me_res = client.get("/api/v1/auth/me", headers=admin_headers)
    if me_res.status_code == 200:
        me_data = me_res.json()
        print(f"  [OK] Auth /me returned authenticated user: {me_data.get('email')} (ID: {me_data.get('id')})")
        results["2_demo_auth"] = "VERIFIED"
    else:
        print(f"  [FAIL] Auth /me failed: {me_res.status_code} {me_res.text}")
        results["2_demo_auth"] = "FAILED"

    # --------------------------------------------------------------------------
    # 3. Verify Workspace and Project Loading
    # --------------------------------------------------------------------------
    print("\n[3/15] Verifying Workspace and Project Loading...")
    proj_res = client.get("/api/v1/projects", headers=admin_headers)
    if proj_res.status_code == 200:
        proj_data = proj_res.json()
        print(f"  [OK] Projects loaded: {proj_data.get('total')} items found in workspace.")
        results["3_projects_loading"] = "VERIFIED"
    else:
        print(f"  [FAIL] Projects query failed: {proj_res.status_code} {proj_res.text}")
        results["3_projects_loading"] = "FAILED"

    # --------------------------------------------------------------------------
    # 4. Upload Actual 1,000-Row Demo CSV
    # --------------------------------------------------------------------------
    print("\n[4/15] Uploading Actual 1,000-Row Demo Customer CSV...")
    demo_csv_path = BASE_DIR / "storage" / "demo" / "demo_customers_1000.csv"
    if not demo_csv_path.exists():
        print(f"  [FAIL] Demo CSV missing at {demo_csv_path}")
        results["4_upload"] = "FAILED"
        return

    raw_bytes_initial = demo_csv_path.read_bytes()
    initial_sha256 = hashlib.sha256(raw_bytes_initial).hexdigest()
    print(f"  [INFO] Initial Demo File SHA-256: {initial_sha256}")

    upload_res = client.post(
        "/api/v1/uploads",
        headers=admin_headers,
        data={"project_id": str(PROJECT_A_ID)},
        files={"file": ("demo_customers_1000.csv", io.BytesIO(raw_bytes_initial), "text/csv")},
    )
    if upload_res.status_code == 201:
        upload_data = upload_res.json()
        upload_id = upload_data["id"]
        server_hash = upload_data["file_hash"]
        print(f"  [OK] Upload successful: Upload ID = {upload_id}")
        print(f"  [OK] Server verified SHA-256 = {server_hash}")
        assert server_hash == initial_sha256, "Server hash mismatch"
        results["4_upload"] = "VERIFIED"
    else:
        print(f"  [FAIL] Upload failed: {upload_res.status_code} {upload_res.text}")
        results["4_upload"] = "FAILED"
        return

    # --------------------------------------------------------------------------
    # 5. Start Real Analysis Run
    # --------------------------------------------------------------------------
    print("\n[5/15] Triggering Real TabularEngine Analysis Run...")
    start_t = time.perf_counter()
    run_res = client.post(
        "/api/v1/runs?sync=true",
        headers=admin_headers,
        json={"project_id": str(PROJECT_A_ID), "upload_id": upload_id},
    )
    elapsed = time.perf_counter() - start_t
    if run_res.status_code == 202:
        run_data = run_res.json()
        run_id = run_data["id"]
        print(f"  [OK] Run started and completed in {elapsed:.3f}s: Status = {run_data['status']}, Stage = {run_data.get('stage')}")
        results["5_run_execution"] = "VERIFIED"
    else:
        print(f"  [FAIL] Run failed: {run_res.status_code} {run_res.text}")
        results["5_run_execution"] = "FAILED"
        return

    # --------------------------------------------------------------------------
    # 6. Verify Actual Summary and Findings
    # --------------------------------------------------------------------------
    print("\n[6/15] Querying Real Summary Metrics and Findings...")
    sum_res = client.get(f"/api/v1/runs/{run_id}/summary", headers=admin_headers)
    summary = sum_res.json()
    print(f"  [INFO] Total Rows: {summary.get('total_rows')}")
    print(f"  [INFO] Clean Rows: {summary.get('clean_rows')}, Dirty Rows: {summary.get('dirty_rows')}")
    print(f"  [INFO] Total Findings: {summary.get('total_findings')}")
    print(f"  [INFO] Quality Score: {summary.get('estimated_quality_score')}%")
    print(f"  [INFO] Severity Distribution: {summary.get('findings_by_severity')}")
    print(f"  [INFO] Category Distribution: {summary.get('findings_by_category')}")

    findings_res = client.get(f"/api/v1/runs/{run_id}/findings?limit=100", headers=admin_headers)
    findings_data = findings_res.json()
    findings = findings_data.get("items", [])
    print(f"  [INFO] Findings Retrieved: {len(findings)} items")

    if (
        summary.get("total_rows") == 1000
        and summary.get("total_columns") == 15
        and summary.get("dirty_rows") > 0
        and len(findings) > 0
    ):
        print("  [OK] Real summary and findings strictly verified.")
        results["6_summary_and_findings"] = "VERIFIED"
    else:
        print("  [FAIL] Summary or findings mismatch.")
        results["6_summary_and_findings"] = "FAILED"

    # --------------------------------------------------------------------------
    # 7. Verify All Eight Detector Categories Executed
    # --------------------------------------------------------------------------
    print("\n[7/15] Verifying All Eight Detector Classes Executed...")
    print(f"  [INFO] Registered Detectors Count: {len(ALL_DETECTORS)}")
    detector_names = [cls.__name__ for cls in ALL_DETECTORS]
    for name in detector_names:
        print(f"    - {name}")

    engine = TabularEngine(storage=LocalStorageService())
    df = pd.read_csv(demo_csv_path)
    executed_detectors = []
    for cls in ALL_DETECTORS:
        det = cls()
        dets = det.detect(df)
        executed_detectors.append((cls.__name__, len(dets)))

    print(f"  [INFO] Detector execution outputs on 1,000 rows:")
    for name, cnt in executed_detectors:
        print(f"    - {name}: {cnt} detections generated")

    if len(executed_detectors) == 8:
        print("  [OK] All eight detector classes executed.")
        results["7_eight_detectors"] = "VERIFIED"
    else:
        results["7_eight_detectors"] = "FAILED"

    # --------------------------------------------------------------------------
    # 8. Open a Finding and Test a Decision
    # --------------------------------------------------------------------------
    print("\n[8/15] Testing Remediation Decision on a Real Finding...")
    target_finding = findings[0]
    finding_id = target_finding["id"]
    print(f"  [INFO] Selected Finding: ID={finding_id}, Category={target_finding['category']}, Title='{target_finding.get('issue_title')}'")

    dec_res = client.post(
        f"/api/v1/findings/{finding_id}/decisions",
        headers=admin_headers,
        json={
            "action_type": target_finding.get("suggested_action", {}).get("action_type") or "transform",
            "custom_parameters": {"note": "Applied via E2E verification test"},
            "notes": "E2E automated review approval",
        },
    )
    if dec_res.status_code == 201:
        dec_data = dec_res.json()
        decision_id = dec_data["id"]
        print(f"  [OK] Decision successfully recorded: Decision ID = {decision_id}, Status = {dec_data['status']}")
        results["8_decision_submission"] = "VERIFIED"
    else:
        print(f"  [FAIL] Decision submission failed: {dec_res.status_code} {dec_res.text}")
        results["8_decision_submission"] = "FAILED"
        decision_id = None

    # --------------------------------------------------------------------------
    # 9. Verify Audit Record is Persisted
    # --------------------------------------------------------------------------
    print("\n[9/15] Verifying Audit Record Persistence...")
    audit_res = client.get(f"/api/v1/runs/{run_id}/audit", headers=admin_headers)
    if audit_res.status_code == 200:
        audit_data = audit_res.json()
        events = audit_data.get("events", [])
        actions = [e["action"] for e in events]
        print(f"  [INFO] Recorded Audit Events ({len(events)}): {actions}")
        if "finding.decided" in actions:
            print("  [OK] 'finding.decided' event verified in immutable audit trail.")
            results["9_audit_persistence"] = "VERIFIED"
        else:
            print("  [FAIL] 'finding.decided' not found in audit events.")
            results["9_audit_persistence"] = "FAILED"
    else:
        print(f"  [FAIL] Audit trail query failed: {audit_res.status_code} {audit_res.text}")
        results["9_audit_persistence"] = "FAILED"

    # --------------------------------------------------------------------------
    # 10. Test Undo Decision
    # --------------------------------------------------------------------------
    print("\n[10/15] Testing Decision Undo...")
    if decision_id:
        undo_res = client.post(f"/api/v1/decisions/{decision_id}/undo", headers=admin_headers)
        if undo_res.status_code == 200:
            undo_data = undo_res.json()
            print(f"  [OK] Decision undone: {undo_data}")
            # Verify audit trail has decision.undone
            re_audit = client.get(f"/api/v1/runs/{run_id}/audit", headers=admin_headers).json()
            re_actions = [e["action"] for e in re_audit.get("events", [])]
            if "decision.undone" in re_actions:
                print("  [OK] 'decision.undone' recorded in audit log.")
                results["10_decision_undo"] = "VERIFIED"
            else:
                print("  [FAIL] 'decision.undone' not found in audit log.")
                results["10_decision_undo"] = "FAILED"
        else:
            print(f"  [FAIL] Undo failed: {undo_res.status_code} {undo_res.text}")
            results["10_decision_undo"] = "FAILED"
    else:
        results["10_decision_undo"] = "SKIPPED_NO_DECISION"

    # --------------------------------------------------------------------------
    # 11. Test CSV, Excel, Parquet Exports Independently & File Parsing
    # --------------------------------------------------------------------------
    print("\n[11/15] Testing CSV, Excel, and Parquet Exports & File Parsing...")
    export_formats = ["csv", "excel", "parquet"]
    export_statuses = {}
    for fmt in export_formats:
        exp_res = client.post(
            f"/api/v1/runs/{run_id}/exports",
            headers=admin_headers,
            json={"format": fmt, "include_cleaned_only": True},
        )
        if exp_res.status_code == 201:
            exp_data = exp_res.json()
            download_url = exp_data.get("download_url")
            print(f"  [INFO] Export ({fmt}): Status 201 Created. download_url = '{download_url}', reported_size = {exp_data.get('file_size_bytes')} bytes")

            # A. Download with valid headers
            dl_res = client.get(download_url, headers=admin_headers)
            if dl_res.status_code == 200 and len(dl_res.content) > 0:
                content_bytes = dl_res.content
                print(f"  [OK] Downloaded {fmt} stream: {len(content_bytes)} bytes received.")

                # B. Inspect file by parsing into DataFrame
                try:
                    stream = io.BytesIO(content_bytes)
                    if fmt == "csv":
                        parsed_df = pd.read_csv(stream)
                    elif fmt == "excel":
                        parsed_df = pd.read_excel(stream, engine="openpyxl")
                    elif fmt == "parquet":
                        parsed_df = pd.read_parquet(stream, engine="pyarrow")

                    print(f"  [OK] Parsed {fmt} successfully: {len(parsed_df)} rows, {len(parsed_df.columns)} columns.")
                    assert len(parsed_df) > 0, "Exported file has 0 rows"
                    assert len(parsed_df.columns) == 15, f"Column count mismatch: {len(parsed_df.columns)}"
                    export_statuses[fmt] = f"VERIFIED ({len(parsed_df)} rows, {len(content_bytes)} bytes)"
                except Exception as parse_err:
                    print(f"  [FAIL] Failed to parse downloaded {fmt} content: {parse_err}")
                    export_statuses[fmt] = f"PARSE_FAILED: {parse_err}"
            elif dl_res.status_code == 404:
                print(f"  [PARTIAL/NOT_IMPLEMENTED] Export ({fmt}) endpoint returns download_url='{download_url}', but download route GET '{download_url}' returns 404 Not Found.")
                export_statuses[fmt] = "NOT IMPLEMENTED (No GET /downloads route)"
            else:
                export_statuses[fmt] = f"FAILED ({dl_res.status_code})"
        else:
            print(f"  [FAIL] Export ({fmt}) creation failed: {exp_res.status_code} {exp_res.text}")
            export_statuses[fmt] = "FAILED"

    # C. Download Security & Tenant Isolation Tests
    print("  [SECURITY] Verifying download route authorization & traversal protection...")
    sample_download = f"/api/v1/downloads/{uuid4()}.csv"
    no_auth_res = client.get(sample_download)
    assert no_auth_res.status_code == 401, f"Expected 401 for unauthenticated download, got {no_auth_res.status_code}"
    print("    [OK] Unauthenticated download request blocked: 401 Unauthorized")

    traversal_res = client.get("/api/v1/downloads/..%2F..%2Fetc%2Fpasswd.csv", headers=admin_headers)
    assert traversal_res.status_code in (400, 404), f"Expected 400/404 for traversal, got {traversal_res.status_code}"
    print("    [OK] Path traversal attempt blocked: 400/404 Bad Request / Not Found")

    results["11_exports"] = export_statuses

    # --------------------------------------------------------------------------
    # 11B. Verify Dataset Comparison Endpoint
    # --------------------------------------------------------------------------
    print("\n[11B] Verifying Dataset Compare Endpoint...")
    cmp_res = client.get(f"/api/v1/runs/{run_id}/compare", headers=admin_headers)
    if cmp_res.status_code == 200:
        cmp_data = cmp_res.json()
        print(f"  [OK] Compare endpoint returned 200 OK: original_rows={cmp_data.get('original_rows_count')}, cleaned_rows={cmp_data.get('cleaned_rows_count')}")
        cols_diff = cmp_data.get("columns_diff", [])
        print(f"  [INFO] Columns diff matrix contains {len(cols_diff)} columns.")
        print(f"  [INFO] Preview original rows: {len(cmp_data.get('preview_original', []))}, Preview cleaned rows: {len(cmp_data.get('preview_cleaned', []))}")
        assert cmp_data.get("original_rows_count") == 1000, "Original row count mismatch in compare"
        assert len(cols_diff) == 15, "Columns diff count mismatch"
        results["11B_compare"] = "VERIFIED"
    else:
        print(f"  [FAIL] Compare endpoint failed: {cmp_res.status_code} {cmp_res.text}")
        results["11B_compare"] = "FAILED"

    # --------------------------------------------------------------------------
    # 12. Verify Original File SHA-256 Remains Unchanged
    # --------------------------------------------------------------------------
    print("\n[12/15] Verifying Original File SHA-256 Immutability...")
    raw_bytes_final = demo_csv_path.read_bytes()
    final_sha256 = hashlib.sha256(raw_bytes_final).hexdigest()
    print(f"  [INFO] Before Analysis SHA-256: {initial_sha256}")
    print(f"  [INFO] After Analysis SHA-256:  {final_sha256}")
    if initial_sha256 == final_sha256:
        print("  [OK] File immutability strictly confirmed: 100% bit-for-bit identical.")
        results["12_file_immutability"] = "VERIFIED"
    else:
        print("  [FAIL] File was mutated on disk!")
        results["12_file_immutability"] = "FAILED"

    # --------------------------------------------------------------------------
    # Summary of Live Verification
    # --------------------------------------------------------------------------
    print("\n" + "=" * 80)
    print("VERIFICATION SUMMARY REPORT:")
    print("=" * 80)
    for k, v in results.items():
        print(f"  {k:30}: {v}")

    return results


if __name__ == "__main__":
    run_e2e_verification()
